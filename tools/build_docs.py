def doc_page(
    app: dict,
    slug: str,
    doc_title: str,
    source: str,
    body: str,
    siblings_present: list,
) -> str:
    canonical = f"{SITE_URL}/{app['slug']}/{slug.replace('.html', '')}"
    name = app["name"]
    description = f"{doc_title} for {name}, a Nexoma Labs LLC application."
    email = app["support_email"]

    siblings = []
    for out, label in siblings_present:
        if out == slug:
            continue
        siblings.append(
            f'<a class="btn btn-secondary btn-sm" href="{out.replace(".html", "")}">{label}</a>'
        )
    siblings.append(
        f'<a class="btn btn-secondary btn-sm" href="{source}">Raw Markdown</a>'
    )

    if app["themed"]:
        breadcrumb = (
            f'<a href="./">{html.escape(name)}</a> <span>/</span> '
            f"<span>{html.escape(doc_title)}</span>"
        )
    else:
        breadcrumb = (
            '<a href="../index.html">Nexoma Labs</a> <span>/</span> '
            f'<a href="./">{html.escape(name)}</a>'
        )

    # If the document states its own date, do not print a second, conflicting one.
    states_own_date = re.search(
        r"last updated|effective date", body[:600], re.IGNORECASE
    )
    date_line = (
        ""
        if states_own_date
        else f"""      <p class="doc-dates">
        Effective {html.escape(app['effective_date'])}
        &middot; Last updated {html.escape(app['updated_date'])}
      </p>"""
    )

    return (
        head(app, f"{doc_title} | {name}", description, canonical, slug)
        + f"""
  <main class="doc-main">
    <article class="doc{'' if app["themed"] else ' container'}">
      <p class="doc-breadcrumb">{breadcrumb}</p>
      <p class="eyebrow">{html.escape(name)}</p>
      <h1>{html.escape(doc_title)}</h1>
{date_line}
      <hr class="doc-rule" />

      <div class="doc-body">
{body}
      </div>

      <aside class="doc-contact">
        <h2>Questions about this document?</h2>
        <p>
          Contact Nexoma Labs LLC at <a href="mailto:{email}">{email}</a>.
        </p>
      </aside>

      <nav class="doc-siblings" aria-label="Related documents">
        {' '.join(siblings)}
      </nav>
    </article>
  </main>
"""
        + footer(app)
    )


def app_index(app: dict) -> str:
    canonical = f"{SITE_URL}/{app['slug']}/"
    name = app["name"]
    cards = []
    for src, out, full in app["present_docs"]:
        cards.append(
            f"""        <article class="doc-card">
          <h3><a href="{out.replace('.html', '')}">{full}</a></h3>
          <p>{html.escape(DOC_BLURBS[src])}</p>
          <p class="doc-card-raw"><a href="{src}">{src}</a></p>
        </article>"""
        )
    return (
        head(
            app,
            f"Documents | {name}",
            f"Privacy policy, terms and support information for {name} by Nexoma Labs LLC.",
            canonical,
        )
        + f"""
  <main class="doc-main">
    <section class="doc{'' if app["themed"] else ' container'}">
      <p class="doc-breadcrumb">
        <a href="{'./' if app['themed'] else '../index.html'}">{html.escape(app['name']) if app['themed'] else 'Nexoma Labs'}</a>
      </p>
      <p class="eyebrow">{html.escape(app['category'])}</p>
      <h1>{html.escape(name)}</h1>
      <p class="lead">{html.escape(app['tagline'])}</p>
      <hr class="doc-rule" />
      <div class="doc-card-grid">
{chr(10).join(cards)}
      </div>
      <aside class="doc-contact">
        <h2>Contact</h2>
        <p>Support for {html.escape(name)}: <a href="mailto:{app['support_email']}">{app['support_email']}</a></p>
      </aside>
    </section>
  </main>
"""
        + footer(app)
    )


