REQUIRED_KEYS = [
    "name",
    "category",
    "tagline",
    "support_email",
    "effective_date",
    "updated_date",
]


class ManifestError(Exception):
    """An app.json is missing, malformed, or incomplete."""


def discover_apps() -> list[dict]:
    apps = []
    for path in sorted(ROOT.iterdir()):
        if not path.is_dir() or path.name.startswith(".") or path.name in RESERVED_DIRS:
            continue
        manifest = path / "app.json"
        if not manifest.exists():
            continue

        rel = manifest.relative_to(ROOT)
        try:
            app = json.loads(manifest.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise ManifestError(f"{rel} is not valid JSON: {exc}") from None
        if not isinstance(app, dict):
            raise ManifestError(f"{rel} must contain a JSON object.")

        missing = [k for k in REQUIRED_KEYS if not str(app.get(k, "")).strip()]
        if missing:
            raise ManifestError(
                f"{rel} is missing required key(s): {', '.join(missing)}\n"
                f"  Required: {', '.join(REQUIRED_KEYS)}"
            )

        app["slug"] = path.name
        app["path"] = path
        app["short_name"] = app.get("short_name") or app["name"]
        app["themed"] = (path / THEME_CSS).exists()
        mark = path / BRAND_FILE
        if mark.exists():
            svg = mark.read_text(encoding="utf-8")
            svg = re.sub(r"<\?xml[^>]*\?>", "", svg).strip()
            # Strip width/height from the ROOT <svg> tag only, so CSS sizes
            # the mark. Child elements keep theirs - removing those would
            # silently erase parts of the drawing.
            def _strip_root(m: re.Match) -> str:
                return re.sub(r'\s+(width|height)="[^"]*"', "", m.group(0))

            svg = re.sub(r"<svg\b[^>]*>", _strip_root, svg, count=1)
            app["brand_mark"] = re.sub(r"\s*\n\s*", " ", svg)
        else:
            app["brand_mark"] = ""
        apps.append(app)
    return apps


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if generated files are out of date instead of writing them",
    )
    args = parser.parse_args()

    try:
        apps = discover_apps()
    except ManifestError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if not apps:
        print("No app directories found (each needs an app.json).", file=sys.stderr)
        return 1

    written: list[Path] = []
    stale: list[Path] = []
    skipped: list[Path] = []

    def emit(target: Path, content: str) -> None:
        current = target.read_text(encoding="utf-8") if target.exists() else None

        # Never overwrite a page someone wrote by hand. Generated pages carry a
        # marker; anything else that already exists is left exactly as it is.
        if current is not None and GENERATED_MARKER not in current:
            skipped.append(target)
            return

        if current == content:
            return
        if args.check:
            stale.append(target)
            return
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        written.append(target)

    for app in apps:
        # Parse every document this app actually ships, first, so each page can
        # link to its siblings by their real titles.
        parsed = []
        for source, out_name, default_title, short in DOC_TYPES:
            md_path = app["path"] / source
            if not md_path.exists():
                if source in REQUIRED_DOCS:
                    print(
                        f"error: {md_path.relative_to(ROOT)} is required but missing.",
                        file=sys.stderr,
                    )
                    return 1
                continue
            body, own_title = markdown_to_html(md_path.read_text(encoding="utf-8"))
            # A document's own H1 wins over the generic label.
            parsed.append((source, out_name, own_title or default_title, body, short))

        app["present_docs"] = [(s, o, title) for s, o, title, _, _ in parsed]
        siblings_present = [(o, title) for _, o, title, _, _ in parsed]
        app["nav_links_for"] = lambda current, docs=parsed: "\n".join(
            '        <li><a href="{}"{}>{}</a></li>'.format(
                o.replace(".html", ""),
                ' aria-current="page"' if o == current else "",
                html.escape(short),
            )
            for _, o, _t, _b, short in docs
        )
        app["footer_docs"] = "\n".join(
            f'            <li><a href="{o.replace(".html", "")}">{html.escape(title)}</a></li>'
            for _, o, title, _b, _s in parsed
        )

        for source, out_name, doc_title, body, _short in parsed:
            emit(
                app["path"] / out_name,
                doc_page(app, out_name, doc_title, source, body, siblings_present),
            )
        emit(app["path"] / "index.html", app_index(app))

    emit(ROOT / "sitemap.xml", sitemap(apps))

    if args.check:
        for path in skipped:
            print(f"kept  {path.relative_to(ROOT)} (hand-authored, not overwritten)")
        if stale:
            for path in stale:
                print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
            print("\nRun: python3 tools/build_docs.py", file=sys.stderr)
            return 1
        print(f"All generated files are up to date ({len(apps)} apps).")
        return 0

    for path in written:
        print(f"wrote {path.relative_to(ROOT)}")
    for path in skipped:
        print(f"kept  {path.relative_to(ROOT)} (hand-authored, not overwritten)")
    print(f"\n{len(written)} file(s) written for {len(apps)} app(s).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
