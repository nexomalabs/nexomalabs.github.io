def sitemap(apps: list[dict]) -> str:
    urls = [(f"{SITE_URL}/", "weekly", "1.0")]
    for app in apps:
        urls.append((f"{SITE_URL}/{app['slug']}/", "monthly", "0.6"))
        for src, out, full in app["present_docs"]:
            urls.append(
                (f"{SITE_URL}/{app['slug']}/{out.replace('.html', '')}", "monthly", "0.5")
            )
    body = "\n".join(
        f"  <url>\n    <loc>{loc}</loc>\n    <changefreq>{freq}</changefreq>\n"
        f"    <priority>{pri}</priority>\n  </url>"
        for loc, freq, pri in urls
    )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f"{GENERATED_MARKER}\n"
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"{body}\n</urlset>\n"
    )


