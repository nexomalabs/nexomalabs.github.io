#!/usr/bin/env python3
"""Generate styled HTML doc pages from the per-app Markdown sources.

Every app directory holds an ``app.json`` plus ``PRIVACY.md``, ``TERMS.md`` and
``SUPPORT.md``. Those Markdown files are the single source of truth: they are
served verbatim at e.g. https://www.nexomalabs.com/hundy/PRIVACY.md and are also
rendered here into ``privacy.html`` / ``terms.html`` / ``support.html``, which are
the URLs submitted to App Store Connect.

Also regenerates each app's index page and sitemap.xml.

Usage:  python3 tools/build_docs.py [--check]

Standard library only. No build pipeline, no dependencies.
"""

